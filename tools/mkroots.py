"""Turn the root certificates in assets/certs/roots.pem into BearSSL trust
anchors: `python tools/mkroots.py assets/certs/roots.pem src/os/TlsRoots.c`.
Each anchor is the certificate's subject name and public key (RSA, or EC on
P-256, P-384 or P-521), as BearSSL's own `brssl ta` writes them. The name line
above each certificate (as in curl's cacert.pem) becomes its comment.
"""
import base64
import sys
from pathlib import Path

RSA = "1.2.840.113549.1.1.1"
EC = "1.2.840.10045.2.1"
CURVES = {  # BearSSL's curve ids
    "1.2.840.10045.3.1.7": 23,  # P-256
    "1.3.132.0.34": 24,  # P-384
    "1.3.132.0.35": 25,  # P-521
}


def tlv(d: bytes, i: int):
    """The element at d[i]: tag, start of its value, end of the element."""
    tag = d[i]
    n = d[i + 1]
    i += 2
    if n & 0x80:
        k = n & 0x7F
        n = int.from_bytes(d[i: i + k], "big")
        i += k
    return tag, i, i + n


def children(d: bytes, start: int, end: int):
    out = []
    while start < end:
        tag, vs, ve = tlv(d, start)
        out.append((tag, start, vs, ve))
        start = ve
    return out


def oid(v: bytes) -> str:
    parts = [v[0] // 40, v[0] % 40]
    n = 0
    for b in v[1:]:
        n = n << 7 | (b & 0x7F)
        if not b & 0x80:
            parts.append(n)
            n = 0
    return ".".join(map(str, parts))


def anchor(der: bytes):
    """(subject name DER, ('rsa', n, e) or ('ec', curve, point))."""
    _, cs, ce = tlv(der, 0)
    _, ts, te = tlv(der, cs)
    tbs = children(der, ts, te)
    if tbs[0][0] == 0xA0:  # [0] version
        tbs = tbs[1:]
    # serial, signature, issuer, validity, subject, subjectPublicKeyInfo
    _, ss, _, se = tbs[4]
    _, _, ks, ke = tbs[5]
    alg, key = children(der, ks, ke)
    algs = children(der, alg[2], alg[3])
    kind = oid(der[algs[0][2]: algs[0][3]])
    bits = der[key[2] + 1: key[3]]  # past the unused-bits count
    if kind == RSA:
        n, e = children(bits, *tlv(bits, 0)[1:])
        mod = bits[n[2]: n[3]].lstrip(b"\0")
        exp = bits[e[2]: e[3]].lstrip(b"\0")
        return der[ss:se], ("rsa", mod, exp)
    if kind == EC:
        curve = oid(der[algs[1][2]: algs[1][3]])
        if curve not in CURVES:
            raise ValueError(f"unsupported curve {curve}")
        return der[ss:se], ("ec", CURVES[curve], bits)
    raise ValueError(f"unsupported key type {kind}")


def read_pem(text: str):
    """(name, DER) for each certificate; the name is the line above the
    "====" line before it, or "" without one."""
    out, lines, name = [], text.splitlines(), ""
    i = 0
    while i < len(lines):
        line = lines[i].strip()
        if line.startswith("===") and i:
            name = lines[i - 1].strip()
        if line == "-----BEGIN CERTIFICATE-----":
            j = i + 1
            while lines[j].strip() != "-----END CERTIFICATE-----":
                j += 1
            der = base64.b64decode("".join(x.strip() for x in lines[i + 1: j]))
            out.append((name, der))
            name = ""
            i = j
        i += 1
    return out


def carray(name: str, data: bytes) -> list:
    out = [f"static const unsigned char {name}[] = {{"]
    for i in range(0, len(data), 12):
        out.append("    " + " ".join(f"0x{b:02X}," for b in data[i: i + 12]))
    out.append("};")
    return out


def main() -> None:
    if len(sys.argv) != 3:
        print("usage: mkroots.py <roots.pem> <out.c>", file=sys.stderr)
        sys.exit(1)
    certs = read_pem(Path(sys.argv[1]).read_text(encoding="ascii"))
    src = sys.argv[1].replace("\\", "/")
    out = [f"/* Generated by tools/mkroots.py from {src}. DO NOT EDIT.",
           " * The root certificates HTTPS trusts; see docs/tls.md. */",
           '#include "bearssl.h"', ""]
    table = []
    for k, (name, der) in enumerate(certs):
        dn, key = anchor(der)
        out.append(f"/* {name} */" if name else f"/* certificate {k + 1} */")
        out += carray(f"dn{k}", dn)
        cast = "(unsigned char *)"
        if key[0] == "rsa":
            out += carray(f"n{k}", key[1])
            out += carray(f"e{k}", key[2])
            table.append(f"    {{{{{cast}dn{k}, sizeof dn{k}}}, BR_X509_TA_CA,\n"
                         f"     {{BR_KEYTYPE_RSA, {{.rsa = {{{cast}n{k}, sizeof n{k},"
                         f"\n                                 {cast}e{k}, "
                         f"sizeof e{k}}}}}}}}},")
        else:
            out += carray(f"q{k}", key[2])
            table.append(f"    {{{{{cast}dn{k}, sizeof dn{k}}}, BR_X509_TA_CA,\n"
                         f"     {{BR_KEYTYPE_EC, {{.ec = {{{key[1]}, {cast}q{k}, "
                         f"sizeof q{k}}}}}}}}},")
        out.append("")
    out.append("const br_x509_trust_anchor tls_roots[] = {")
    out += table
    out.append("};")
    out.append("const unsigned tls_roots_count = "
               "sizeof tls_roots / sizeof tls_roots[0];")
    Path(sys.argv[2]).write_bytes(("\n".join(out) + "\n").encode("ascii"))
    print(f"{len(certs)} roots -> {sys.argv[2]}")


if __name__ == "__main__":
    main()
