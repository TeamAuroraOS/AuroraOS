#!/usr/bin/env python3
"""Writes a C header with the few assets.pak entries the launcher draws.

The launcher (src/main.c, built into the FIRM) used to read the pack from the
SD card at start-up, which meant initialising the card before the menu could
show. Embedding these entries, still RLE-compressed, removes that wait.

usage: mklauncherassets.py Aurora/assets.pak [include/asset_ids.h] > header
Without a usable pack it writes an empty list and the launcher falls back to
its built-in icons and font.
"""
import os
import re
import struct
import sys

NEEDED = [
    "ASSET_WALLPAPER",
    "ASSET_FONT_SMALL", "ASSET_FONT_UI", "ASSET_FONT_BOLD", "ASSET_FONT_TITLE",
    "ASSET_ICON_POWER_32", "ASSET_ICON_POWER_48", "ASSET_ICON_POWER_64",
    "ASSET_ICON_SETTINGS_32", "ASSET_ICON_SETTINGS_48",
    "ASSET_ICON_SETTINGS_64",
    "ASSET_ICON_DISPLAY_32",
]
MAGIC = 0x4B415041  # "APAK"


def parse_ids(path):
    text = open(path).read()
    ids = {m.group(1): int(m.group(2))
           for m in re.finditer(r"#define\s+(ASSET_\w+)\s+(\d+)u", text)}
    total = int(re.search(r"#define\s+ASSET_COUNT\s+(\d+)u", text).group(1))
    return ids, total


def emit(entries):
    out = ["/* Generated by tools/mklauncherassets.py. DO NOT EDIT. */",
           "#ifndef LAUNCHER_ASSETS_H", "#define LAUNCHER_ASSETS_H", ""]
    for n, (_name, _id, _t, _w, _h, _us, blob) in enumerate(entries):
        out.append("static const unsigned char lp_%d[] = {" % n)
        for i in range(0, len(blob), 16):
            out.append("  " + ", ".join("0x%02X" % b for b in blob[i:i + 16])
                       + ",")
        out.append("};")
    out.append("")
    out.append("/* id, type, w, h, compressed size, size, data */")
    out.append("#define LAUNCHER_ASSET_LIST \\")
    for n, (name, aid, t, w, h, us, blob) in enumerate(entries):
        out.append("  {%du, %d, %d, %d, sizeof(lp_%d), %du, lp_%d}, /* %s */ \\"
                   % (aid, t, w, h, n, us, n, name))
    out.append("  {0xFFFFFFFFu, 0, 0, 0, 0, 0, 0}")
    out.append("")
    out.append("#endif")
    sys.stdout.write("\n".join(out) + "\n")


def main():
    pak = sys.argv[1]
    ids_path = sys.argv[2] if len(sys.argv) > 2 else "include/asset_ids.h"
    ids, total = parse_ids(ids_path)
    if not os.path.exists(pak):
        sys.stderr.write("mklauncherassets: %s not found, launcher keeps its "
                         "built-in art\n" % pak)
        emit([])
        return
    data = open(pak, "rb").read()
    magic, version, count, data_off, _arena = struct.unpack_from("<5I", data, 0)
    if magic != MAGIC or version != 1 or count != total:
        sys.stderr.write("mklauncherassets: %s does not match this build "
                         "(run make assets), launcher keeps its built-in "
                         "art\n" % pak)
        emit([])
        return
    table = {}
    for i in range(count):
        eid, t, w, h, _pad, off, csize, usize = struct.unpack_from(
            "<IHHHHIII", data, 32 + 24 * i)
        table[eid] = (t, w, h, off, csize, usize)
    entries = []
    for name in NEEDED:
        aid = ids[name]
        t, w, h, off, csize, usize = table[aid]
        entries.append((name, aid, t, w, h, usize, data[off:off + csize]))
    emit(entries)
    sys.stderr.write("mklauncherassets: %d entries, %d bytes compressed\n"
                     % (len(entries), sum(len(e[6]) for e in entries)))


main()
